export function convertToCSV(data: RawTransaction[]): string {
  const headers = [
    'order_id',
    'order_date',
    'customer_id',
    'customer_name',
    'customer_age',
    'customer_gender',
    'city',
    'state',
    'country',
    'product_id',
    'product_name',
    'category',
    'sub_category',
    'quantity',
    'unit_price',
    'unit_cost',
    'discount_percent',
    'payment_method',
    'order_status',
  ];

  const rows = data.map((row) => [
    row.order_id,
    row.order_date,
    row.customer_id,
    `"${row.customer_name}"`,
    row.customer_age === null ? '' : row.customer_age,
    row.customer_gender,
    `"${row.city}"`,
    row.state,
    row.country,
    row.product_id,
    `"${row.product_name}"`,
    row.category,
    `"${row.sub_category}"`,
    row.quantity,
    row.unit_price,
    row.unit_cost,
    row.discount_percent,
    row.payment_method,
    row.order_status,
  ]);

  return [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
}
